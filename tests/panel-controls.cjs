const fs=require('node:fs');
const assert=require('node:assert/strict');
const src=fs.readFileSync('superpostal.js','utf8');
const begin=src.indexOf('// FLOATING SIDE PANEL');
const end=src.indexOf('// TEMPORARY, DEVICE-LOCAL CLIENT TOTALS',begin);
assert.ok(begin>=0&&end>begin,'totals panel exists');
const panel=src.slice(begin,end);
assert.doesNotMatch(panel,/createElement\(['"]img['"]\)|media\.discordapp\.net\/attachments|drive\.google\.com\/thumbnail/i,'panel creates no decorative images or image requests');
assert.match(panel,/heading\.textContent='CLIENT TOTALS'/,'yellow header title remains');
assert.match(panel,/background:#f2b32e/,'yellow header remains');
assert.match(panel,/width:'320px'/,'panel width remains');
assert.match(panel,/minHeight:'240px'/,'panel min height remains');
assert.match(panel,/function dockToApproval\(\)/,'responsive docking function remains');
assert.match(panel,/box\.style\.width=panelWidth\+'px'/,'responsive panel sizing remains');
assert.match(panel,/const reference=visibleTopReference\(target\)/,'panel aligns to Job State header');
assert.match(panel,/scheduleDock\(\)/,'docking is scheduled');
assert.match(panel,/document\.body\.appendChild\(box\)/,'totals panel is mounted');
assert.match(src, /function spClientLedger\(\)/,'client ledger still exists');
new Function(src);
console.log('PASS: no decorative image; totals panel, header, docking and ledger retained.');
